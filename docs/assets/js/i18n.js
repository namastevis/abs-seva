export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const text = t(el.dataset.i18n);
    if (!text.includes('🎤')) { el.textContent = text; return; }
    // Show the same mic icon as the buttons next to each field, not the emoji
    el.textContent = '';
    text.split('🎤').forEach((part, i) => {
      if (i) el.insertAdjacentHTML('beforeend', MIC_ICON);
      el.append(part);
    });
  });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); el.setAttribute('aria-label', t(el.dataset.i18nTitle)); });
}

