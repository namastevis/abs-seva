/** Convert Odia / Bengali-Assamese / Devanagari digits to ASCII */
export function toAsciiDigits(str) {
  return String(str).replace(/[०-९০-৯୦-୯]/g, (ch) => {
    const c = ch.charCodeAt(0);
    return String(c - (c >= 0x0B66 ? 0x0B66 : c >= 0x09E6 ? 0x09E6 : 0x0966));
  });
}
